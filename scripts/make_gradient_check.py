"""Write solver_py/tests/reference/gradient_check.json: index-gradient values from the Python
rasteriser's profile function. The TypeScript tests must reproduce them (geometry.ts).
Run: .venv/bin/python scripts/make_gradient_check.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "solver_py"))
from modesolver.raster import gradient_profile  # noqa: E402

rows = []
for profile in ("exponential", "gaussian", "erfc", "linear"):
    for d in (-0.5, 0.0, 0.3, 1.0, 2.5, 7.0):
        for length in (0.5, 2.0):
            rows.append({"profile": profile, "d": d, "length": length, "value": float(gradient_profile(profile, d, length))})
out = {"_comment": "Generated by scripts/make_gradient_check.py. Do not edit by hand.", "values": rows}
(ROOT / "solver_py/tests/reference/gradient_check.json").write_text(json.dumps(out, indent=1) + "\n")
print(len(rows), "values written")
