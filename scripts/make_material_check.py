"""Write solver_py/tests/reference/material_check.json: indices of every library material at a
few wavelengths, computed by the Python evaluator. The TypeScript tests read this file and
must reproduce every value, which keeps the two implementations in agreement.
Run: .venv/bin/python scripts/make_material_check.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "solver_py"))
from modesolver.materials import index_tensor, load_library  # noqa: E402

WAVELENGTHS = [0.532, 0.78, 1.064, 1.31, 1.55, 2.0]
rows = []
for mid in sorted(load_library()):
    for lam in WAVELENGTHS:
        # With the optic axis along x: n_x is "along" (n_e for uniaxial), n_y is "across" (n_o).
        nx, ny, _ = index_tensor(mid, lam, optic_axis="x")
        rows.append({"material": mid, "lambda": lam, "alongOpticAxis": nx.real, "acrossOpticAxis": ny.real})
out = {"_comment": "Generated by scripts/make_material_check.py. Do not edit by hand.", "values": rows}
(ROOT / "solver_py/tests/reference/material_check.json").write_text(json.dumps(out, indent=1) + "\n")
print(len(rows), "values written")
